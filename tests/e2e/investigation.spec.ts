import { expect, test } from '@playwright/test';
import { folder, openApp, openFile, unlockBackup } from './helpers';
test('잠금 본문을 숨기고 오답에서 복구하며 중복 수집을 막는다', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button', { name: '새 게임', exact: true }).click();
  const personal = await openFile(page, 'F03');
  await expect(personal).not.toContainText('정산표가 내가 확인한 것과 달라졌다');
  await page.screenshot({ path: testInfo.outputPath('locked.png') });
  await personal.getByRole('textbox').fill('417');
  await personal.getByRole('button', { name: '잠금 해제' }).click();
  await expect(personal.getByRole('status')).toContainText('비밀번호가 맞지 않아');
  await personal.getByRole('textbox').fill('０４１７');
  await personal.getByRole('button', { name: '잠금 해제' }).click();
  await expect(personal).toContainText('정산표가 내가 확인한 것과 달라졌다');
  const explorer = await folder(page, '백업');
  await expect(page.locator('body')).not.toContainText('정산_원본.csv');
  await explorer.getByRole('textbox').fill('TEAL-04');
  await explorer.getByRole('button', { name: '잠금 해제' }).click();
  await expect(explorer.getByRole('status')).toContainText('비밀번호가 맞지 않아');
  await unlockBackup(page);
  const original = await openFile(page, 'F08');
  await expect(original.getByRole('table')).toContainText('800,000');
  await original.getByRole('button', { name: /^증거 기록/ }).click();
  await expect(original.getByRole('button', { name: /^기록됨/ })).toBeDisabled();
  const notebook = await openApp(page, '조사 노트');
  await expect(notebook.getByText('기록한 증거 1개')).toBeVisible();
});

test('대화 선택·스크롤과 증거 원본 이동을 유지하고 창을 닫아도 메모를 보존한다', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '새 게임', exact: true }).click();
  let messenger = await openApp(page, '메신저');
  await expect(messenger).not.toContainText('온라인');
  await messenger.getByRole('button', { name: /민지와 서윤/ }).click();
  const history = messenger.getByRole('region', { name: '대화 기록', exact: true });
  await history.evaluate(element => { element.scrollTop = element.scrollHeight; });
  const position = await history.evaluate(element => element.scrollTop);
  expect(position).toBeGreaterThan(0);
  await messenger.getByRole('button', { name: /^증거 기록/ }).click();
  await messenger.getByRole('button', { name: /너와 서윤/ }).click();
  await messenger.getByRole('button', { name: /민지와 서윤/ }).click();
  await expect.poll(() => history.evaluate(element => element.scrollTop)).toBe(position);
  messenger = await openApp(page, '메신저');
  await expect(messenger.getByRole('button', { name: /민지와 서윤/ })).toHaveAttribute('aria-pressed', 'true');
  await messenger.getByRole('button', { name: /너와 서윤/ }).click();
  const notebook = await openApp(page, '조사 노트');
  await notebook.getByRole('button', { name: '원본 다시 열기', exact: true }).click();
  await expect(messenger.getByRole('button', { name: /민지와 서윤/ })).toHaveAttribute('aria-pressed', 'true');
  await messenger.getByRole('button', { name: /너와 서윤/ }).click();
  await openApp(page, '조사 노트');
  await notebook.getByRole('button', { name: '원본 다시 열기', exact: true }).click();
  await expect(messenger.getByRole('button', { name: /민지와 서윤/ })).toHaveAttribute('aria-pressed', 'true');
  const map = await openFile(page, 'F06');
  await map.getByRole('button', { name: /^증거 기록/ }).click();
  await map.getByRole('button', { name: '별관_안내도.svg 닫기', exact: true }).click();
  const note = (await openApp(page, '조사 노트')).getByRole('textbox', { name: '나의 추리 메모' });
  await note.fill('창을 닫아도 남는 기록');
  await notebook.getByRole('button', { name: '조사 노트 닫기', exact: true }).click();
  const reopened = await openApp(page, '조사 노트');
  await expect(reopened).toContainText('기록한 증거 2개');
  await expect(reopened.getByRole('textbox', { name: '나의 추리 메모' })).toHaveValue('창을 닫아도 남는 기록');
});
